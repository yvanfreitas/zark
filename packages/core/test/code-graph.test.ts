describe('buildGraph', () => {
  // Two components in memory: `a` calls into `b`, plus a self-call that must be dropped.
  const sources: Record<string, string> = {
    'a/main.ts': `import { B } from '../b/b';\nexport function run(b: B) { b.go(); b.nope(); run(b); }`,
    'b/b.ts': `export class B { go() {} }`,
  };
  const facts = new Map(Object.entries(sources).map(([p, t]) => [p, extractModule(p, t)]));
  const owner = new Map([['a/main.ts', 'a'], ['b/b.ts', 'b']]);

  it('cross-component edge uses id prefix', () => {
    const { graph } = buildGraph('a', ['a/main.ts'], facts, owner, { paths: [] });
    expect(graph.edges).toEqual([
      { from: 'a/main.ts#run', to: 'b:b/b.ts#B', kind: 'calls', count: 1 }, // `nope` is not a member: the class itself
      { from: 'a/main.ts#run', to: 'b:b/b.ts#B.go', kind: 'calls', count: 1 },
    ]);
    expect(graph.modules).toEqual([{ path: 'a/main.ts', pieces: [{ name: 'run', kind: 'function' }] }]);
  });

  const single = (text: string) => {
    const facts = new Map([['m.ts', extractModule('m.ts', text)]]);
    return buildGraph('a', ['m.ts'], facts, new Map([['m.ts', 'a']]), { paths: [] }).graph;
  };

  it('calls to local helpers are internal', () => {
    const graph = single(`function helper() {}\nclass Local { m() {} }\nexport function run() { helper(); const l = new Local(); l.m(); console.log(); }`);
    expect(graph.edges).toEqual([]);
    expect(graph.unresolved).toEqual({ calls: 1, external: 0, unowned: 0 }); // only the global console.log
  });

  it('member call on untyped module-scope variable stays unresolved', () => {
    const graph = single(`const client = makeClient();\nlet other;\nconst fn = () => 1;\nnamespace N { export function f() {} }\nexport function run() { client.send(); other.go(); fn(); N.f(); }`);
    expect(graph.edges).toEqual([]);
    // makeClient (global), client.send, other.go; fn() and N.f() are internal
    expect(graph.unresolved).toEqual({ calls: 3, external: 0, unowned: 0 });
  });

  it('piece called by its local name resolves to the piece', () => {
    const graph = single(`export default class Foo { static make() {} }\nconst a = () => 1;\nexport { a as b };\nexport function run() { Foo.make(); new Foo(); a(); }`);
    expect(graph.edges).toEqual([
      { from: 'm.ts#run', to: 'm.ts#b', kind: 'calls', count: 1 },
      { from: 'm.ts#run', to: 'm.ts#default', kind: 'instantiates', count: 1 },
      { from: 'm.ts#run', to: 'm.ts#default.make', kind: 'calls', count: 1 },
    ]);
    expect(graph.unresolved.calls).toBe(0);
  });

  it('a constructor call site is attributed to the class, which has no constructor member', () => {
    const graph = single(`export function go() {}\nexport class C { constructor() { go(); } run() { go(); } }`);
    expect(graph.edges).toEqual([
      { from: 'm.ts#C', to: 'm.ts#go', kind: 'calls', count: 1 },
      { from: 'm.ts#C.run', to: 'm.ts#go', kind: 'calls', count: 1 },
    ]);
  });

  it('a call into a repo file no component claims is unowned, never parsed', () => {
    const { graph } = buildGraph('a', ['a/main.ts'], facts, new Map([['a/main.ts', 'a']]), { paths: [] }, new Set(['a/main.ts', 'b/b.ts']));
    expect(graph.edges).toEqual([]);
    expect(graph.unresolved).toEqual({ calls: 0, external: 0, unowned: 2 });
  });
});

describe('scanProject', () => {
  it('graph of bot component matches snapshot', async () => {
    const root = await copyFixture();
    const result = await scanProject(arch(root), {});
    expect(result.problems).toEqual([]);
    expect(await graphText(root, 'bot')).toBe(BOT_YAML);
    expect(result.components.map((c) => [c.id, c.file, c.status])).toEqual([
      ['bot', 'code/bot.yaml', 'written'],
      ['moderation', 'code/moderation.yaml', 'written'],
    ]);
    const bot = result.components[0];
    expect([bot.modules, bot.pieces, bot.edges, bot.parseErrors]).toEqual([4, 6, 12, 0]);
    // Canonical (`zark fmt --check` stays green) and loadable as a code file.
    expect(formatText('code', BOT_YAML)).toBe(BOT_YAML);
    const project = await loadProject(arch(root));
    expect(project.files.get('code/bot.yaml')!.error).toBeUndefined();
    expect(project.codeGraphs.get('bot')!.graph.edges).toHaveLength(12);
  });

  it('unowned and external counts', async () => {
    const root = await copyFixture();
    const { components } = await scanProject(arch(root), {});
    expect(components.find((c) => c.id === 'bot')!.unresolved).toEqual({ calls: 2, external: 2, unowned: 1 }); // console.log, m.trim; setup() is internal
    expect(components.find((c) => c.id === 'moderation')!.unresolved).toEqual({ calls: 0, external: 0, unowned: 1 });
    expect(await graphText(root, 'moderation')).toContain('members: [ classify ]'); // private `secret` left out
  });

  it('scan twice gives identical bytes', async () => {
    const root = await copyFixture();
    await scanProject(arch(root), {});
    const first = await graphText(root, 'bot');
    const again = await scanProject(arch(root), {});
    expect(again.components.map((c) => c.status)).toEqual(['unchanged', 'unchanged']);
    expect(await graphText(root, 'bot')).toBe(first);
  });

  it('crlf and backslash paths give identical output', async () => {
    const lf = await copyFixture();
    await scanProject(arch(lf), {});
    const crlf = await copyFixture();
    for (const f of ['handler.ts', 'helpers.ts', 'logger.ts', 'orchestrator.ts']) {
      const p = join(crlf, 'services', 'bot', 'src', f);
      await writeFile(p, (await readFile(p, 'utf8')).replace(/\r?\n/g, '\r\n'));
    }
    // Forward slashes on Windows, backslashes elsewhere: whichever the OS does not hand out natively.
    const dir = process.platform === 'win32' ? arch(crlf).replaceAll('\\', '/') : arch(crlf);
    await scanProject(dir, {});
    expect(await graphText(crlf, 'bot')).toBe(await graphText(lf, 'bot'));
    expect(await graphText(crlf, 'bot')).not.toMatch(/\r|\\/);
  });

  it('check reports stale after a source edit and clean after rescan', async () => {
    const root = await copyFixture();
    const missing = await scanProject(arch(root), { check: true });
    expect(missing.components.map((c) => c.status)).toEqual(['stale', 'stale']);
    expect(await readdir(arch(root))).not.toContain('code'); // check writes nothing
    await scanProject(arch(root), {});
    const helpers = join(root, 'services', 'bot', 'src', 'helpers.ts');
    await writeFile(helpers, `${await readFile(helpers, 'utf8')}export function extra() {}\n`);
    const dirty = await scanProject(arch(root), { check: true });
    expect(dirty.components.map((c) => [c.id, c.status])).toEqual([['bot', 'stale'], ['moderation', 'unchanged']]);
    await scanProject(arch(root), {});
    const clean = await scanProject(arch(root), { check: true });
    expect(clean.components.map((c) => c.status)).toEqual(['unchanged', 'unchanged']);
  });

  it('component without source deletes its old file', async () => {
    const root = await copyFixture();
    await scanProject(arch(root), {});
    const entity = join(arch(root), 'entities', 'moderation.yaml');
    await writeFile(entity, (await readFile(entity, 'utf8')).replace(/^source:.*\n/m, ''));
    const checked = await scanProject(arch(root), { check: true });
    expect(checked.components.find((c) => c.id === 'moderation')!.status).toBe('stale');
    const result = await scanProject(arch(root), {});
    expect(result.components.find((c) => c.id === 'moderation')).toMatchObject({ file: 'code/moderation.yaml', status: 'deleted' });
    expect(await readdir(join(arch(root), 'code'))).toEqual(['bot.yaml']);
  });

  it('a generated file that cannot be read (not missing) fails the scan', async () => {
    const root = await copyFixture();
    await mkdir(join(arch(root), 'code', 'bot.yaml'), { recursive: true }); // EISDIR, not ENOENT
    await expect(scanProject(arch(root), { check: true })).rejects.toThrow(/EISDIR/);
  });

  it('uses an already-loaded project instead of loading it again', async () => {
    const root = await copyFixture();
    const project = await loadProject(arch(root));
    // Drop moderation's source on disk after loading: the passed-in project must win.
    const entity = join(arch(root), 'entities', 'moderation.yaml');
    await writeFile(entity, (await readFile(entity, 'utf8')).replace(/^source:.*\n/m, ''));
    const result = await scanProject(arch(root), { project });
    expect(result.components.map((c) => [c.id, c.status])).toEqual([['bot', 'written'], ['moderation', 'written']]);
  });

  it('warns when an explicit code.tsconfig is missing', async () => {
    const root = await copyFixture();
    await writeFile(join(arch(root), 'zark.yaml'), 'schema: 1\nname: X\ncode:\n  tsconfig: nope/tsconfig.json\n');
    const { warnings, problems } = await scanProject(arch(root), {});
    expect(problems).toEqual([]);
    expect(warnings).toEqual(['code.tsconfig: nope/tsconfig.json is not found; path aliases are not resolved']);
    // The default tsconfig.json stays silent when absent.
    await writeFile(join(arch(root), 'zark.yaml'), 'schema: 1\nname: X\n');
    await rm(join(root, 'tsconfig.json'), { force: true });
    expect((await scanProject(arch(root), {})).warnings).toEqual([]);
  });

  it('only scans the listed components', async () => {
    const root = await copyFixture();
    const result = await scanProject(arch(root), { only: ['moderation'] });
    expect(result.components.map((c) => c.id)).toEqual(['moderation']);
    expect(await readdir(join(arch(root), 'code'))).toEqual(['moderation.yaml']);
  });
});
